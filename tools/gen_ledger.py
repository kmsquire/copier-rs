"""Generate notes/TEST_LEDGER.md from the Python and Rust test modules.

Run from anywhere: `python3 tools/gen_ledger.py`.
"""
import glob
import os
import re

# The Python checkout is the parent of this crate.
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CRATE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Python tests with no Rust counterpart at all.
NOT_PORTED = {
    ("test_tools", "test_types"): "runs mypy on the Python sources",
    ("test_config", "test_flags_bad_data"): "pydantic type errors; rejected at compile time in Rust",
    ("test_config", "test_flags_extra_fails"): "unknown keyword argument; rejected at compile time in Rust",
    ("test_jinja2_env", "*"): "probes Python objects (PurePath.parser, SettingsModel) inside the Jinja sandbox",
}


def main() -> None:
    rows, details, totals = [], [], [0, 0, 0, 0]
    for py in sorted(glob.glob(f"{ROOT}/tests/test_*.py")):
        module = os.path.basename(py)[:-3]
        names = re.findall(r"^def (test_\w+)\(", open(py).read(), flags=re.M)
        rs_path = f"{CRATE}/tests/{module}.rs"
        rs = open(rs_path).read() if os.path.exists(rs_path) else ""
        ignored = {name: reason for reason, name in re.findall(r'#\[ignore = "([^"]*)"\][^{;]*?fn (test_\w+)', rs)}
        conditional = set(re.findall(r"#\[cfg_attr\([^\]]*ignore[^\]]*\)\]\s*fn (test_\w+)", rs))
        active = skipped = absent = 0
        for name in names:
            if name in ignored:
                skipped += 1
                details.append(f"| {module} | {name} | ignored | {ignored[name]} |")
            elif re.search(rf"fn {name}\(", rs):
                active += 1
                if name in conditional:
                    details.append(f"| {module} | {name} | active | ignored on one platform, see the attribute |")
            else:
                absent += 1
                why = NOT_PORTED.get((module, name)) or NOT_PORTED.get((module, "*")) or "MISSING"
                details.append(f"| {module} | {name} | not ported | {why} |")
        rows.append(f"| {module} | {len(names)} | {active} | {skipped} | {absent} |")
        for index, value in enumerate((len(names), active, skipped, absent)):
            totals[index] += value
    out = """# Test ledger

Every Python test function, by module, and what became of it. Generated by
`tools/gen_ledger.py`; regenerate after changing tests.

- `active`: ported and running in `cargo test`.
- `ignored`: ported but not run by default; the reason is the `#[ignore]` text.
  `network` tests pass with `cargo test -- --include-ignored`.
- `not ported`: no Rust meaning.

| Module | Python tests | active | ignored | not ported |
|---|---|---|---|---|
"""
    out += "\n".join(rows)
    out += f"\n| **total** | **{totals[0]}** | **{totals[1]}** | **{totals[2]}** | **{totals[3]}** |\n"
    out += "\n## Tests that are not simply active\n\n| Module | Test | Status | Reason |\n|---|---|---|---|\n"
    out += "\n".join(details) + "\n"
    open(f"{CRATE}/notes/TEST_LEDGER.md", "w").write(out)
    print(totals, [d for d in details if "MISSING" in d])


if __name__ == "__main__":
    main()
